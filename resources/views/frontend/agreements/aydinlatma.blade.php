        <h2>Giriş</h2>
        <p>Gps Yazılı Teknoloji Danışmanlık Ve Lojistik hizmetleri limited şirketi ("Şirket") olarak; kişisel verilerinizin gizliliği ve güvenliği en önemli önceliklerimiz arasındadır. Şirketimiz, 6698 sayılı Kişisel Verilerin Korunması Kanunu ("KVKK") düzenlemelerine uyumlu olarak kişisel verilerinizi işlemektedir. Kişisel verileriniz, kimliğinizi belirli ya da belirlenebilir kılan her türlü bilgi anlamına gelmektedir.</p>

