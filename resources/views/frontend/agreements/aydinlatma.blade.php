        <h2>Kişisel Verilerin Aktarıldığı Kişi / Kurum Grupları</h2>
        <p>Şirketimiz, veri minimizasyonu ve gerekli güvenlik önlemlerini sağlayarak kişisel verilerinizi aşağıdaki alıcı grupları ile paylaşabilmektedir:</p>

        <ul>
            <li>İştirakler, iş ortakları ve hizmet sağlayıcılar (pazarlama amacıyla — açık rıza ile)</li>
            <li>Yetkili kamu kurum ve kuruluşları (kanunda öngörülmesi hâlinde)</li>
            <li>Avukatlar, denetçiler, vergi ve siber güvenlik danışmanları (hukuki ve denetim amaçlarıyla)</li>
            <li>Ürün satıcıları, kurye ve lojistik sağlayıcılar (siparişlerin teslimi ve sözleşmenin ifası için)</li>
            <li>Çağrı merkezi ve müşteri destek hizmeti sağlayıcıları</li>
            <li>Bağımsız denetim, mali müşavirlik, e‑fatura iş ortakları, özel entegratörler ve teknoloji sağlayıcıları</li>
            <li>Potansiyel alıcılar ve işlemin muhatapları (şirket birleşme/devralma durumlarında)</li>
        </ul>

        <p>Yurt dışına aktarım gerektiğinde, KVKK ve ilgili yönetmeliklere uygun olarak standart sözleşmeler veya mevzuatta öngörülen diğer uygun güvenceler sağlanarak aktarım yapılacaktır.</p>

        <h2>Veri Güvenliği Önlemleri</h2>
        <p>Şirket, veri sorumlusu olarak aşağıdaki teknik ve idari tedbirleri uygulamaktadır:</p>
        <ul>
            <li>Periyodik sızma testleri ve ulusal/uluslararası teknik standartlara uygun güvenlik uygulamaları</li>
            <li>Web sitesi, mobil site ve uygulamalarda SSL/TLS koruması</li>
            <li>Periyodik risk analizleri ve risk azaltma aksiyonları</li>
            <li>Erişim ve yetki kontrolleri</li>
            <li>Kişisel veri işleme politikalarının düzenli güncellenmesi</li>
        </ul>

        <h2>Haklarınız</h2>
        <p>Kişisel veri sahipleri olarak KVKK kapsamında aşağıdaki haklara sahipsiniz:</p>
        <ul>
            <li>Kişisel verilerinizin işlenip işlenmediğini öğrenme</li>
            <li>İşlenmişse buna ilişkin bilgi talep etme</li>
            <li>İşlenme amacını ve amacına uygun kullanılıp kullanılmadığını öğrenme</li>
            <li>Yurt içine/yurt dışına aktarıldığı üçüncü kişileri bilme</li>
            <li>Eksik ya da yanlış işlenmişse düzeltilmesini isteme</li>
            <li>KVKK'da öngörülen şartlarda silinmesini veya yok edilmesini isteme</li>
            <li>Düzeltme/silme/yok etme işlemlerinin üçüncü kişilere bildirilmesini isteme</li>
            <li>Münhasıran otomatik sistemlerle analiz edilerek aleyhinize bir sonucun ortaya çıkmasına itiraz etme</li>
            <li>İlgili mevzuata aykırı işleme sebebiyle zarara uğramanız hâlinde tazminat talep etme</li>
        </ul>

